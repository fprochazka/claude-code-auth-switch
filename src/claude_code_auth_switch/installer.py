# Files that Claude Code writes via atomic temp+rename (breaks symlinks)
COPY_FILES = [
    "settings.json",
    "settings.local.json",
    "keybindings.json",
]


def resolve_copy_files(source_dir: Path) -> list[str]:
    """COPY_FILES plus every top-level *.md file in source_dir."""
    md_files = sorted(p.name for p in source_dir.glob("*.md") if p.is_file())
    seen: set[str] = set()
    result: list[str] = []
    for name in [*COPY_FILES, *md_files]:
        if name in seen:
            continue
        seen.add(name)
        result.append(name)
    return result


# Directories that are safe to symlink (files inside are real)
SYMLINK_DIRS = [
    "commands",
    "skills",
    "agents",
    "plugins",
    "projects",
    "scripts",
]

# Settings keys that mirror the shared plugins/ directory, copied from source_dir on every install.
PLUGIN_SETTINGS_KEYS = ("enabledPlugins", "extraKnownMarketplaces")

# Profile root files that an install changes are backed up below the profile root. The tool never deletes them.
BACKUPS_DIR_NAME = ".auth-switch-backups"


def resolve_command(name: str) -> Path:
    """Find a console script of this package on PATH, so that generated files can call it by absolute path.

    `uv tool install` puts the scripts into ~/.local/bin as symlinks into the tool environment. The
    symlink path stays the same across upgrades, so it is not resolved further.
    """
    found = shutil.which(name)
    if found is None:
        print(f"Error: {name} is not on PATH.", file=sys.stderr)
        print(
            "Install the tool with `uv tool install`, see the README, and make sure its bin directory is on PATH.",
            file=sys.stderr,
        )
        sys.exit(1)
    return Path(os.path.abspath(found))


class ProfileBackup:
    """Backups of existing profile root files that an install run changes, in <profile>/.auth-switch-backups/<UTC timestamp>/.

    Every write to an existing file goes through save() first: copied files, the settings.json
    patches and the mcpServers sync. A run can write one file twice (a copy, then the patch); only
    the content from before the run is kept, and a file that the run created is not backed up. The directory is created only when a file is
    backed up, so a run that changes nothing leaves no trace. It sits below the profile root and keeps the file names, so Claude Code does not load a
    backed-up CLAUDE.md as instructions. The tool never deletes a backup; the user removes them.
    """

    def __init__(self, profile_dir: Path, stamp: str):
        self.root = profile_dir / BACKUPS_DIR_NAME
        self.stamp = stamp
        self.directory: Path | None = None
        self.saved: set[str] = set()

    def created(self, path: Path) -> None:
        """Note a file this run created, so later writes in the same run do not back it up."""
        self.saved.add(path.name)

    def save(self, path: Path) -> None:
        if path.name in self.saved:
            return
        self.saved.add(path.name)
        if self.directory is None:
            self.directory = self.root / self.stamp
            counter = 1
            while self.directory.exists():
                self.directory = self.root / f"{self.stamp}-{counter}"
                counter += 1
            self.directory.mkdir(parents=True)
        target = self.directory / path.name
        shutil.copy2(path, target)
        print(f"  backed up {path.name} to {target}")


TEMP_MARKER = ".cc-auth-switch-tmp-"


def current_umask() -> int:
    mask = os.umask(0)
    os.umask(mask)
    return mask


def write_profile_file(path: Path, content: bytes, backup: ProfileBackup | None, new_mode: int | None = None) -> bool:
    """Write a file in a profile's root; the only way the installer changes one. Return whether it changed.

    The final content goes to a temp file next to the target first. When its bytes equal the target,
    nothing happens: no backup, no output. Otherwise the old target goes into the run's backup and the
    temp file replaces it atomically, keeping the target's mode (.claude.json is 0600). A new file gets
    new_mode, or the umask default. The temp name starts with a dot and never ends in .md or .json, so
    Claude Code does not load it if the process dies in between.
    """
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}{TEMP_MARKER}", dir=path.parent)
    temp = Path(temp_name)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        try:
            current = path.read_bytes()
        except FileNotFoundError:
            current = None
        if current == content:
            temp.unlink()
            return False
        if current is not None:
            mode = stat.S_IMODE(path.stat().st_mode)
            if backup is not None:
                backup.save(path)
        else:
            mode = new_mode if new_mode is not None else 0o666 & ~current_umask()
            if backup is not None:
                backup.created(path)
        os.chmod(temp, mode)
        os.replace(temp, path)
        return True
    except BaseException:
        temp.unlink(missing_ok=True)
        raise


def expected_copy(
    source_dir: Path, filename: str, profile_config: dict[str, Any], shared: SharedPatches | None
) -> bytes:
    """Content that a profile file has right after a sync, patches included."""
    if filename == "settings.json":
        expected = build_expected_settings(source_dir / filename, profile_config, shared)
        if expected is not None:
            return expected.encode()
    return (source_dir / filename).read_bytes()


def read_source_plugin_keys(source_dir: Path) -> dict[str, Any] | None:
    """Read enabledPlugins and extraKnownMarketplaces from source_dir's settings.json.

    A missing file means no plugins, so the profiles lose the keys too. An unreadable file returns
    None, so a broken source never wipes the profiles' plugin settings.
    """
    path = source_dir / "settings.json"
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text())
    except (json.JSONDecodeError, OSError):
        return None
    if not isinstance(data, dict):
        return None
    return {key: data[key] for key in PLUGIN_SETTINGS_KEYS if key in data}


def check_plugin_overrides(
    profile_name: str, profile_config: dict[str, Any], source_dir: Path, source_plugin_keys: dict[str, Any] | None
) -> None:
    """Validate profiles.<name>.plugins, and warn about enabled plugins that Claude Code cannot install."""
    overrides = profile_config.get("plugins")
    if overrides is None:
        return
    if not isinstance(overrides, dict):
        print(
            f"Error: Profile '{profile_name}' has plugins: {overrides!r}, expected a map of \"<plugin>@<marketplace>\" to true or false",
            file=sys.stderr,
        )
        sys.exit(1)
    for plugin_id, enabled in overrides.items():
        parts = plugin_id.split("@") if isinstance(plugin_id, str) else []
        if len(parts) != 2 or not all(parts):
            print(
                f"Error: Profile '{profile_name}' has plugins key {plugin_id!r}, expected \"<plugin>@<marketplace>\"",
                file=sys.stderr,
            )
            sys.exit(1)
        if not isinstance(enabled, bool):
            print(
                f"Error: Profile '{profile_name}' has plugins value {enabled!r} for '{plugin_id}', expected true or false",
                file=sys.stderr,
            )
            sys.exit(1)

    known = set()
    declared = (source_plugin_keys or {}).get("extraKnownMarketplaces")
    if isinstance(declared, dict):
        known |= set(declared)
    try:
        installed = json.loads((source_dir / "plugins" / "known_marketplaces.json").read_text())
        if isinstance(installed, dict):
            known |= set(installed)
    except (OSError, json.JSONDecodeError):
        pass
    for plugin_id, enabled in overrides.items():
        marketplace = plugin_id.split("@")[1]
        if enabled and marketplace not in known:
            print(
                f"Warning: Profile '{profile_name}' enables {plugin_id}, but the marketplace '{marketplace}' is neither in "
                f"extraKnownMarketplaces of {source_dir / 'settings.json'} nor in plugins/known_marketplaces.json, so Claude Code cannot install it",
                file=sys.stderr,
            )


def share_sessions_flag(profile_name: str, profile_config: dict[str, Any]) -> bool:
    value = profile_config.get("share_sessions", False)
    if not isinstance(value, bool):
        print(f"Error: Profile '{profile_name}' has share_sessions: {value!r}, expected true or false", file=sys.stderr)
        sys.exit(1)
    return value


def setup_shared_sessions(profile_name: str, profile_dir: Path, share: bool) -> None:
    target = sessions.shared_sessions_dir()
    if not share:
        sessions.warn_if_still_shared(profile_name, profile_dir, target)
        return
    try:
        sessions.ensure_shared(profile_name, profile_dir, target)
    except sessions.SessionsError as error:
        print(f"Error: Profile '{profile_name}': {error}", file=sys.stderr)
        sys.exit(1)


def setup_profile_dir(
    profile_name: str,
    profile_dir: Path,
    source_dir: Path,
    force_sync: bool,
    profile_config: dict[str, Any] | None = None,
    shared: SharedPatches | None = None,
    backup: ProfileBackup | None = None,
) -> None:
    profile_dir.mkdir(parents=True, exist_ok=True)
    profile_config = profile_config or {}

    # Copy mutable files, with the settings.json patches already applied. A sync writes only files
    # whose bytes change, so a regular unattended sync stays quiet.
    for filename in resolve_copy_files(source_dir):
        src = source_dir / filename
        dst = profile_dir / filename
        if not src.exists():
            continue
        if dst.exists() and not force_sync:
            continue
        content = expected_copy(source_dir, filename, profile_config, shared)
        if write_profile_file(dst, content, backup, new_mode=stat.S_IMODE(src.stat().st_mode)):
            print(f"  {'synced' if force_sync else 'copied'} {filename}")

    # Create directory symlinks
    for dirname in SYMLINK_DIRS:
        src = source_dir / dirname
        dst = profile_dir / dirname
        if not src.exists():
            continue
        if dst.is_symlink():
            # Update symlink if target changed
            if dst.resolve() == src.resolve():
                continue
            dst.unlink()
        elif dst.exists():
            # Real directory exists, skip (don't replace user data with symlink)
            print(f"  skipped {dirname}/ (real directory exists, not replacing with symlink)")
            continue
        dst.symlink_to(src)
        print(f"  symlinked {dirname}/ -> {src}")


def sync_mcp_servers(
    profile_name: str,
    profile_dir: Path,
    source_claude_json_path: Path,
    backup: ProfileBackup | None = None,
) -> None:
    """Sync mcpServers from the global ~/.claude.json into a profile's .claude.json.

    Only the mcpServers key is synced — all other keys in the profile's
    .claude.json are preserved untouched.
    """
    if not source_claude_json_path.exists():
        return

    try:
        source_data = json.loads(source_claude_json_path.read_text())
    except (json.JSONDecodeError, OSError):
        return

    source_servers = source_data.get("mcpServers")
    if source_servers is None:
        return

    profile_claude_json = profile_dir / ".claude.json"
    if not profile_claude_json.exists():
        return

    try:
        profile_data = json.loads(profile_claude_json.read_text())
    except (json.JSONDecodeError, OSError):
        return

    existing_servers = profile_data.get("mcpServers")

    # .claude.json is live state that running sessions rewrite all the time, in their own formatting.
    # Only a change of mcpServers is a reason to rewrite it, never a formatting difference.
    if existing_servers == source_servers:
        return

    # Warn about profile-only servers being overwritten
    if existing_servers and isinstance(existing_servers, dict):
        source_names = set(source_servers.keys()) if isinstance(source_servers, dict) else set()
        profile_only = set(existing_servers.keys()) - source_names
        if profile_only:
            print(f"  note: overwriting profile-only mcpServers: {', '.join(sorted(profile_only))}")

    profile_data["mcpServers"] = source_servers
    if not write_profile_file(profile_claude_json, (json.dumps(profile_data, indent=2) + "\n").encode(), backup):
        return

    server_count = len(source_servers) if isinstance(source_servers, dict) else 0
    print(f"  synced mcpServers ({server_count} server{'s' if server_count != 1 else ''})")


def is_session_start_hook(hook: object) -> bool:
    """Tell whether a hook entry runs our SessionStart command, at any path."""
    if not isinstance(hook, dict) or not isinstance(command := hook.get("command"), str):
        return False
    try:
        words = shlex.split(command)
    except ValueError:
        return LEGACY_SESSION_START_HOOK_NAME in command or f"{TOOL_COMMAND_NAME} {SESSION_START_SUBCOMMAND}" in command
    if not words:
        return False
    program = os.path.basename(words[0])
    if program == LEGACY_SESSION_START_HOOK_NAME:
        return True
    return program == TOOL_COMMAND_NAME and words[1:2] == [SESSION_START_SUBCOMMAND]


def merge_session_start_hook(data: dict[str, Any], hook_command: str) -> None:
    """Own exactly one SessionStart matcher group in data["hooks"], identified by its command.

    Every entry that runs our command is dropped, so a moved tool replaces its old path, and ours is
    appended. Entries of other tools stay as they are, because Claude Code runs all of them.
    """
    hooks = data.get("hooks")
    if not isinstance(hooks, dict):
        hooks = {}
    groups = hooks.get("SessionStart")
    kept: list[Any] = []
    for group in groups if isinstance(groups, list) else []:
        if isinstance(group, dict) and isinstance(group.get("hooks"), list):
            inner = [hook for hook in group["hooks"] if not is_session_start_hook(hook)]
            if len(inner) != len(group["hooks"]):
                if not inner:
                    continue
                group = {**group, "hooks": inner}
        kept.append(group)
    kept.append(
        {
            "matcher": "",
            "hooks": [{"type": "command", "command": hook_command, "timeout": SESSION_START_HOOK_TIMEOUT_SECONDS}],
        }
    )
    data["hooks"] = {**hooks, "SessionStart": kept}


@dataclass(frozen=True)
class SharedPatches:
    """Inputs of the settings.json patches that are the same for every profile of one install run."""

    session_start_hook: str | None = None
    # enabledPlugins and extraKnownMarketplaces of source_dir's settings.json; a key absent there is
    # absent here. None when that file cannot be read, which leaves the profiles' keys alone.
    source_plugin_keys: dict[str, Any] | None = None


def apply_plugin_keys(data: dict[str, Any], profile_config: dict[str, Any], source_plugin_keys: dict[str, Any]) -> None:
    """Copy the two plugin keys whole from source_dir's settings.json, then apply the profile's overrides.

    plugins/ is shared through a symlink, so what is installed is global, but Claude Code loads a
    plugin only when enabledPlugins in the profile's own settings.json says true.
    """
    for key in PLUGIN_SETTINGS_KEYS:
        if key in source_plugin_keys:
            data[key] = copy.deepcopy(source_plugin_keys[key])
        else:
            data.pop(key, None)
    overrides = profile_config.get("plugins") or {}
    if overrides:
        enabled = data.get("enabledPlugins")
        data["enabledPlugins"] = {**(enabled if isinstance(enabled, dict) else {}), **overrides}


def apply_profile_patches(data: dict[str, Any], profile_config: dict[str, Any], shared: SharedPatches | None) -> None:
    """Apply the config-driven changes of a profile's settings.json, shared by the install and the divergence check."""
    shared = shared or SharedPatches()
    if (attribution := profile_config.get("attribution")) is not None:
        data["attribution"] = attribution
    if (plans_directory := profile_config.get("plansDirectory")) is not None:
        data["plansDirectory"] = os.path.expanduser(plans_directory)
    elif isinstance(existing := data.get("plansDirectory"), str):
        data["plansDirectory"] = os.path.expanduser(existing)
    if shared.source_plugin_keys is not None:
        apply_plugin_keys(data, profile_config, shared.source_plugin_keys)
    if shared.session_start_hook is not None:
        merge_session_start_hook(data, shared.session_start_hook)


def patch_settings_json(
    profile_name: str,
    profile_dir: Path,
    profile_config: dict[str, Any],
    shared: SharedPatches | None = None,
    backup: ProfileBackup | None = None,
) -> None:
    """Patch per-profile settings (attribution, plansDirectory, plugins, the SessionStart hook) into settings.json."""
    settings_path = profile_dir / "settings.json"
    data: object = {}
    if settings_path.exists():
        try:
            data = json.loads(settings_path.read_text())
        except (json.JSONDecodeError, OSError):
            return
    if not isinstance(data, dict):
        return

    original = copy.deepcopy(data)
    apply_profile_patches(data, profile_config, shared)
    if not data and not settings_path.exists():
        return

    if not write_profile_file(settings_path, (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode(), backup):
        return
    changed = [key for key in data if data.get(key) != original.get(key)] or ["formatting"]
    print(f"  patched {', '.join(changed)} in settings.json")


def generate_launcher_script(profile_name: str, description: str, tool_command: Path, config_path: Path) -> str:
    """The claude-<profile> launcher. All launch logic lives in `cc-auth-switch start`, which reads the config on every launch."""
    command = shlex.join([str(tool_command), "start", "--config", str(config_path), profile_name])
    return (
        "\n".join(
            [
                "#!/usr/bin/env bash",
                MARKER,
                # A newline in the description would end the comment and run the rest as a command.
                f"# Profile: {profile_name} — {' '.join(str(description).splitlines())}",
                f'exec {command} "$@"',
            ]
        )
        + "\n"
    )


def install_launcher_script(script_path: Path, content: str) -> None:
    script_path.parent.mkdir(parents=True, exist_ok=True)

    existing = None
    if script_path.exists():
        existing = script_path.read_text()

    if existing == content:
        return

    script_path.write_text(content)
    script_path.chmod(script_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"  installed {script_path}")


def is_legacy_uv_entry_point(path: Path, name: str) -> bool:
    """Tell whether a bin entry is a symlink that uv made to a command of an older version of this tool."""
    if not path.is_symlink():
        return False
    target = Path(os.readlink(path))
    return (
        target.name == name and target.parent.name == "bin" and target.parent.parent.name == "claude-code-auth-switch"
    )


def cleanup_legacy_commands(bin_dir: Path) -> None:
    """Remove commands that earlier versions left in bin_dir, but only those that are clearly ours."""
    helper = bin_dir / LEGACY_ATTRIBUTION_HELPER_NAME
    if helper.is_symlink():
        if is_legacy_uv_entry_point(helper, LEGACY_ATTRIBUTION_HELPER_NAME):
            helper.unlink()
            print(f"  removed old {helper}")
        else:
            print(f"  warning: left {helper} in place, it is not a command that this tool installed")
    elif helper.is_file():
        if hashlib.sha256(helper.read_bytes()).hexdigest() in LEGACY_ATTRIBUTION_HELPER_SHA256:
            helper.unlink()
            print(f"  removed old {helper}")
        else:
            print(f"  warning: left {helper} in place, its content differs from every version that install.py wrote")

    for name in (LEGACY_SESSION_START_HOOK_NAME, LEGACY_TOOL_COMMAND_NAME):
        path = bin_dir / name
        if is_legacy_uv_entry_point(path, name):
            path.unlink()
            print(f"  removed old {path}")
        elif path.is_symlink() or path.exists():
            print(f"  warning: left {path} in place, it is not a command that this tool installed")


def cleanup_stale_scripts(bin_dir: Path, active_script_names: set[str]) -> None:
    if not bin_dir.exists():
        return
    for entry in bin_dir.iterdir():
        if not entry.is_file():
            continue
        if entry.name in active_script_names:
            continue
        try:
            content = entry.read_text()
        except (OSError, UnicodeDecodeError):
            continue
        if MARKER in content:
            entry.unlink()
            print(f"  removed stale script {entry}")


def build_expected_settings(
    source_path: Path, profile_config: dict[str, Any], shared: SharedPatches | None = None
) -> str | None:
    """Build what a profile's settings.json should look like after patching.

    Applies config-driven patches (like attribution) to the source content,
    so that divergence detection only flags truly unexpected changes.
    """
    if not source_path.exists():
        return None

    try:
        data = json.loads(source_path.read_text())
    except (json.JSONDecodeError, OSError):
        return None

    if not isinstance(data, dict):
        return None
    apply_profile_patches(data, profile_config, shared)

    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def collect_diverged_files(
    config: dict[str, Any],
    profiles_base: Path,
    source_dir: Path,
    shared: SharedPatches | None = None,
) -> list[tuple[str, str, str]]:
    """Check all profile copy files for divergence from source.

    Returns list of (profile_name, filename, diff_text) for files where
    the profile copy contains content not present in the source.
    For settings.json, the expected content includes config-driven patches
    (e.g. attribution), so those don't count as divergence.
    """
    diverged = []
    copy_files = resolve_copy_files(source_dir)
    for profile_name, profile_config in config["profiles"].items():
        profile_config = profile_config or {}
        profile_dir = profiles_base / profile_name
        for filename in copy_files:
            src = source_dir / filename
            dst = profile_dir / filename
            if not src.exists() or not dst.exists():
                continue

            if filename == "settings.json":
                expected = build_expected_settings(src, profile_config, shared)
                if expected is None:
                    continue
                src_lines = expected.splitlines(keepends=True)
            else:
                src_lines = src.read_text().splitlines(keepends=True)

            dst_lines = dst.read_text().splitlines(keepends=True)
            diff = list(
                difflib.unified_diff(
                    src_lines,
                    dst_lines,
                    fromfile=str(src),
                    tofile=str(dst),
                )
            )
            if not diff:
                continue
            # Check if profile has any additions (content not in source)
            has_additions = any(line.startswith("+") and not line.startswith("+++") for line in diff)
            if has_additions:
                diverged.append((profile_name, filename, "".join(diff)))
    return diverged


class SectionOutput(contextlib.AbstractContextManager["SectionOutput"]):
    """Pass stdout through and remember whether a section printed anything, for the "nothing changed" line."""

    def __init__(self) -> None:
        self.printed = False
        self._target = sys.stdout
        self._redirect = contextlib.redirect_stdout(self)

    def write(self, text: str) -> int:
        if text.strip():
            self.printed = True
        return self._target.write(text)

    def flush(self) -> None:
        self._target.flush()

    def __enter__(self) -> SectionOutput:
        self._target = sys.stdout
        self._redirect.__enter__()
        return self

    def __exit__(
        self, exc_type: type[BaseException] | None, exc: BaseException | None, traceback: TracebackType | None
    ) -> None:
        self._redirect.__exit__(exc_type, exc, traceback)


def install(config_arg: Path | None, sync: bool, force: bool) -> None:
    config_path, config = read_config(config_arg)
    # The launchers pass this path to `start`, so it must not depend on the directory they run in.
    config_path = Path(os.path.abspath(config_path))
    source_dir = expand_path(config.get("source_dir", str(DEFAULT_SOURCE_DIR)))
    bin_dir = expand_path(config.get("bin_dir", str(DEFAULT_BIN_DIR)))
    profiles_base = expand_path(config.get("profiles_dir", str(DEFAULT_PROFILES_DIR)))

    secrets_path = secrets_path_for(config_path)
    secrets: dict[str, dict[str, str]] = {}
    if secrets_path.exists():
        check_secrets_git_safety(secrets_path)
        secrets = load_secrets(secrets_path, config)

    if not source_dir.exists():
        print(f"Error: Source directory not found: {source_dir}", file=sys.stderr)
        sys.exit(1)

    tool_command = resolve_command(TOOL_COMMAND_NAME)
    session_start_hook = f"{shlex.quote(str(tool_command))} {SESSION_START_SUBCOMMAND}"
    source_plugin_keys = read_source_plugin_keys(source_dir)
    # start validates the roles on every launch too; this reports a broken role before anything is written.
    try:
        resolve_roles(config)
    except ConfigError as error:
        print(f"Error: {config_path}: {error}", file=sys.stderr)
        sys.exit(1)
    for profile_name, profile_config in config["profiles"].items():
        # The launcher resolves the profile again on every start; resolving it here reports a broken
        # profile at install time instead of at its first launch, and before anything is written.
        try:
            launcher.resolve_profile(config, secrets, profiles_base, profile_name)
        except ConfigError as error:
            print(f"Error: {config_path}: {error}", file=sys.stderr)
            sys.exit(1)
        check_plugin_overrides(profile_name, profile_config or {}, source_dir, source_plugin_keys)
    shared = SharedPatches(session_start_hook, source_plugin_keys)

    # When --sync is used without --force, check for diverged files first
    if sync and not force:
        diverged = collect_diverged_files(config, profiles_base, source_dir, shared)
        if diverged:
            print("\nDiverged profile files detected:\n")
            for profile_name, filename, diff_text in diverged:
                print(f"  Profile '{profile_name}' — {filename}:")
                for line in diff_text.splitlines():
                    print(f"    {line}")
                print()
            print("The profile file(s) above contain changes not present in the source.")
            print("You probably want to merge these changes back to the source file first.")
            print("\nTo overwrite anyway, use: cc-auth-switch install --sync --force")
            sys.exit(0)

    source_claude_json_path = Path.home() / ".claude.json"
    backup_stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backups: list[ProfileBackup] = []
    active_script_names: set[str] = set()

    for profile_name, profile_config in config["profiles"].items():
        profile_config = profile_config or {}
        description = profile_config.get("description", "")
        share = share_sessions_flag(profile_name, profile_config)

        profile_dir = profiles_base / profile_name
        script_name = f"claude-{profile_name}"
        script_path = bin_dir / script_name
        active_script_names.add(script_name)

        print(f"\nProfile: {profile_name}")
        with SectionOutput() as section:
            # Setup profile directory with copies and symlinks
            backup = ProfileBackup(profile_dir, backup_stamp)
            backups.append(backup)
            setup_profile_dir(profile_name, profile_dir, source_dir, sync, profile_config, shared, backup)

            # Share sessions/ with plain claude and the other sharing profiles, or warn that it still is
            setup_shared_sessions(profile_name, profile_dir, share)

            # Patch attribution settings and the SessionStart hook into profile's settings.json
            patch_settings_json(profile_name, profile_dir, profile_config, shared, backup)

            # Sync mcpServers from global ~/.claude.json
            sync_mcp_servers(profile_name, profile_dir, source_claude_json_path, backup)

            # Install the launcher, which runs `cc-auth-switch start <profile>`
            install_launcher_script(
                script_path, generate_launcher_script(profile_name, description, tool_command, config_path)
            )
        if not section.printed:
            print("  in sync, nothing changed")

    # Clean up launchers of removed profiles, also the bash wrappers of earlier versions
    print("\nCleanup:")
    with SectionOutput() as section:
        cleanup_stale_scripts(bin_dir, active_script_names)
        cleanup_legacy_commands(bin_dir)
    if not section.printed:
        print("  nothing to clean up")

    print("\nDone.")
    if any(backup.directory is not None for backup in backups):
        print(
            f"Backups of replaced files are in <profile>/{BACKUPS_DIR_NAME}/. cc-auth-switch never deletes them; remove them with rm when you no longer need them."
        )


def rollback_sessions(config_arg: Path | None, profile_name: str) -> None:
    config_path, config = read_config(config_arg)
    if profile_name not in config["profiles"]:
        print(f"Error: Profile '{profile_name}' is not defined in {config_path}", file=sys.stderr)
        sys.exit(1)
    profile_config = config["profiles"][profile_name] or {}
    profiles_base = expand_path(config.get("profiles_dir", str(DEFAULT_PROFILES_DIR)))
    profile_dir = profiles_base / profile_name
    target = sessions.shared_sessions_dir()

    try:
        owned = sessions.rollback(profile_name, profile_dir, target)
    except sessions.SessionsError as error:
        print(f"Error: Profile '{profile_name}': {error}", file=sys.stderr)
        sys.exit(1)

    print(f"Profile {profile_name}: sessions/ is a real directory again.")
    print(f"  moved {len(owned.live)} file(s) of live sessions back from {target}")
    print(f"  deleted {len(owned.dead)} file(s) of ended sessions from {target}")
    if share_sessions_flag(profile_name, profile_config):
        print(f"  warning: share_sessions is still true in {config_path}; the next install shares sessions/ again")
