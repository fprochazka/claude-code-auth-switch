"""
Claude Code Multi-Account Profile Manager

Reads ~/.claude/auth-switch.yaml and creates isolated profile directories
with shared configuration, then installs wrapper scripts to bin_dir.
"""

import json
import os
import difflib
import shutil
import stat
import subprocess
import sys
from pathlib import Path

import yaml

MARKER = "# Generated by claude-code-auth-switch"

# Console script of this package; each wrapper runs it at launch to read attribution from git config.
ATTRIBUTION_HELPER_NAME = "claude-auth-switch-attribution"

# Files that Claude Code writes via atomic temp+rename (breaks symlinks)
COPY_FILES = [
    "settings.json",
    "settings.local.json",
    "keybindings.json",
]


def resolve_copy_files(source_dir: Path) -> list[str]:
    """COPY_FILES plus every top-level *.md file in source_dir."""
    md_files = sorted(p.name for p in source_dir.glob("*.md") if p.is_file())
    seen: set[str] = set()
    result: list[str] = []
    for name in [*COPY_FILES, *md_files]:
        if name in seen:
            continue
        seen.add(name)
        result.append(name)
    return result

# Directories that are safe to symlink (files inside are real)
SYMLINK_DIRS = [
    "commands",
    "skills",
    "agents",
    "plugins",
    "projects",
    "scripts",
]

DEFAULT_CONFIG_PATH = Path("~/.claude/auth-switch.yaml").expanduser()
# Kept working so an existing install does not break when ~/.claude/auth-switch.yaml is absent.
LEGACY_CONFIG_PATH = Path("~/.claude-profiles/config.yaml").expanduser()
DEFAULT_SOURCE_DIR = Path("~/.claude").expanduser()
DEFAULT_BIN_DIR = Path("~/.local/bin").expanduser()
DEFAULT_PROFILES_DIR = Path("~/.claude-profiles").expanduser()

# Model classes whose alias (sonnet/opus/haiku/fable) can be pinned to a specific
# version id via the corresponding ANTHROPIC_DEFAULT_<CLASS>_MODEL env var.
VALID_MODEL_CLASSES = ("sonnet", "opus", "haiku", "fable")


def load_config(config_path: Path) -> dict:
    with open(config_path) as f:
        config = yaml.safe_load(f)
    if not config or "profiles" not in config:
        print(f"Error: No profiles defined in {config_path}", file=sys.stderr)
        sys.exit(1)
    return config


def resolve_config_path(cli_arg: Path | None, new_default: Path, legacy_default: Path) -> Path:
    """Pick the config file to read.

    An explicit --config always wins, even when it does not exist, so the caller reports the
    path the user actually asked for. Otherwise the new default wins, and the legacy path is
    only used when the new default is absent.
    """
    if cli_arg is not None:
        return cli_arg.expanduser()
    if new_default.exists():
        return new_default
    if legacy_default.exists():
        print(
            f"Note: using legacy config {legacy_default} — the preferred location is {new_default}",
            file=sys.stderr,
        )
        return legacy_default
    return new_default


def secrets_path_for(config_path: Path) -> Path:
    """Sibling secrets file: auth-switch.yaml -> auth-switch.secrets.yaml."""
    return config_path.with_name(f"{config_path.stem}.secrets.yaml")


def check_secrets_git_safety(secrets_path: Path) -> None:
    """Refuse to run when the secrets file could reach a git remote.

    Tracked file -> fatal. Inside a repo but not ignored -> fatal. Outside a repo, or without a
    git binary, there is nothing to check. Git output stays captured so no path or content leaks.
    """
    directory = str(secrets_path.parent)
    name = str(secrets_path)

    def run(*git_args: str) -> int | None:
        try:
            return subprocess.run(
                ["git", "-C", directory, *git_args],
                capture_output=True,
            ).returncode
        except FileNotFoundError:
            return None

    tracked = run("ls-files", "--error-unmatch", name)
    if tracked is None:
        return
    if tracked == 0:
        print(f"Error: Secrets file {secrets_path} is tracked in git.", file=sys.stderr)
        print(f"Remove it from the index and ignore it:", file=sys.stderr)
        print(f"  git -C {directory} rm --cached {secrets_path.name}", file=sys.stderr)
        print(f"  echo '{secrets_path.name}' >> {secrets_path.parent / '.gitignore'}", file=sys.stderr)
        sys.exit(1)
    if tracked == 128:
        return

    ignored = run("check-ignore", "-q", name)
    if ignored in (0, 128, None):
        return
    print(f"Error: Secrets file {secrets_path} is inside a git repository but is not ignored.", file=sys.stderr)
    print(f"Add it to .gitignore before running the installer:", file=sys.stderr)
    print(f"  echo '{secrets_path.name}' >> {secrets_path.parent / '.gitignore'}", file=sys.stderr)
    sys.exit(1)


def load_secrets(secrets_path: Path, config: dict) -> dict[str, dict[str, str]]:
    """Read the secrets file into {profile_name: {env_key: value}}.

    The file mirrors the main config but allows only profiles.<name>.env with string values.
    Anything else aborts the install, so a typo cannot silently drop a credential.
    """
    with open(secrets_path) as f:
        data = yaml.safe_load(f)
    if data is None:
        return {}

    def fatal(message: str) -> None:
        print(f"Error: {secrets_path}: {message}", file=sys.stderr)
        sys.exit(1)

    if not isinstance(data, dict):
        fatal("expected a mapping with a single top-level 'profiles' key")
    if extra := sorted(set(data) - {"profiles"}):
        fatal(f"only the top-level key 'profiles' is allowed, found: {', '.join(extra)}")

    profiles = data.get("profiles") or {}
    if not isinstance(profiles, dict):
        fatal("'profiles' must be a mapping of profile name to settings")

    secrets: dict[str, dict[str, str]] = {}
    for profile_name, profile_config in profiles.items():
        if profile_name not in config["profiles"]:
            fatal(f"profile '{profile_name}' is not defined in the main config")
        if profile_config is None:
            continue
        if not isinstance(profile_config, dict):
            fatal(f"profile '{profile_name}' must be a mapping containing only 'env'")
        if extra := sorted(set(profile_config) - {"env"}):
            fatal(f"profile '{profile_name}' may only contain 'env', found: {', '.join(extra)}")
        env = profile_config.get("env") or {}
        if not isinstance(env, dict):
            fatal(f"profile '{profile_name}': 'env' must be a mapping of variable name to string value")
        for key, value in env.items():
            if not isinstance(key, str):
                fatal(f"profile '{profile_name}': env variable names must be strings")
            if not isinstance(value, str):
                fatal(f"profile '{profile_name}': env value for '{key}' must be a string (quote it in YAML)")
        secrets[profile_name] = dict(env)
    return secrets


def merge_secret_env(profile_name: str, env_vars: dict[str, str], secret_env: dict[str, str]) -> dict[str, str]:
    """Merge secret env vars into a profile's env, rejecting keys defined in both files.

    A key in both places has no obvious winner, so the install stops instead of guessing.
    The value is never printed — only the profile and the variable name.
    """
    if collisions := sorted(set(env_vars) & set(secret_env)):
        for key in collisions:
            print(
                f"Error: Profile '{profile_name}' defines env var '{key}' in both the config "
                f"and the secrets file — keep it in exactly one of them",
                file=sys.stderr,
            )
        sys.exit(1)
    return {**env_vars, **secret_env}


def expand_path(path_str: str) -> Path:
    return Path(os.path.expanduser(path_str))


def pinned_models_to_env(profile_name: str, pinned_models: dict) -> dict[str, str]:
    """Translate a profile's pinned_models mapping into ANTHROPIC_DEFAULT_<CLASS>_MODEL env vars.

    Each entry pins what a model-class alias (sonnet/opus/haiku/fable) resolves to. An unknown
    class key or a non-string / empty version aborts the whole install (same fatal style as load_config).
    """
    env: dict[str, str] = {}
    for model_class, version in pinned_models.items():
        if model_class not in VALID_MODEL_CLASSES:
            print(
                f"Error: Profile '{profile_name}' has unknown pinned_models class '{model_class}' "
                f"(valid classes: {', '.join(VALID_MODEL_CLASSES)})",
                file=sys.stderr,
            )
            sys.exit(1)
        if not isinstance(version, str) or not version.strip():
            print(
                f"Error: Profile '{profile_name}' has invalid pinned_models value for '{model_class}': "
                f"expected a non-empty model version id string",
                file=sys.stderr,
            )
            sys.exit(1)
        env[f"ANTHROPIC_DEFAULT_{model_class.upper()}_MODEL"] = version
    return env


def resolve_command(name: str) -> Path:
    """Find a console script of this package on PATH, so that generated files can call it by absolute path.

    `uv tool install` puts the scripts into ~/.local/bin as symlinks into the tool environment. The
    symlink path stays the same across upgrades, so it is not resolved further.
    """
    found = shutil.which(name)
    if found is None:
        print(f"Error: {name} is not on PATH.", file=sys.stderr)
        print("Install the tool with `uv tool install`, see the README, and make sure its bin directory is on PATH.", file=sys.stderr)
        sys.exit(1)
    return Path(os.path.abspath(found))


def setup_profile_dir(
    profile_name: str,
    profile_dir: Path,
    source_dir: Path,
    force_sync: bool,
) -> None:
    profile_dir.mkdir(parents=True, exist_ok=True)

    # Copy mutable files
    for filename in resolve_copy_files(source_dir):
        src = source_dir / filename
        dst = profile_dir / filename
        if not src.exists():
            continue
        if dst.exists() and not force_sync:
            continue
        shutil.copy2(str(src), str(dst))
        print(f"  {'synced' if force_sync else 'copied'} {filename}")

    # Create directory symlinks
    for dirname in SYMLINK_DIRS:
        src = source_dir / dirname
        dst = profile_dir / dirname
        if not src.exists():
            continue
        if dst.is_symlink():
            # Update symlink if target changed
            if dst.resolve() == src.resolve():
                continue
            dst.unlink()
        elif dst.exists():
            # Real directory exists, skip (don't replace user data with symlink)
            print(f"  skipped {dirname}/ (real directory exists, not replacing with symlink)")
            continue
        dst.symlink_to(src)
        print(f"  symlinked {dirname}/ -> {src}")


def sync_mcp_servers(
    profile_name: str,
    profile_dir: Path,
    source_claude_json_path: Path,
) -> None:
    """Sync mcpServers from the global ~/.claude.json into a profile's .claude.json.

    Only the mcpServers key is synced — all other keys in the profile's
    .claude.json are preserved untouched.
    """
    if not source_claude_json_path.exists():
        return

    try:
        source_data = json.loads(source_claude_json_path.read_text())
    except (json.JSONDecodeError, OSError):
        return

    source_servers = source_data.get("mcpServers")
    if source_servers is None:
        return

    profile_claude_json = profile_dir / ".claude.json"
    if not profile_claude_json.exists():
        return

    try:
        profile_data = json.loads(profile_claude_json.read_text())
    except (json.JSONDecodeError, OSError):
        return

    existing_servers = profile_data.get("mcpServers")

    # Check if already in sync
    if existing_servers == source_servers:
        return

    # Warn about profile-only servers being overwritten
    if existing_servers and isinstance(existing_servers, dict):
        source_names = set(source_servers.keys()) if isinstance(source_servers, dict) else set()
        profile_only = set(existing_servers.keys()) - source_names
        if profile_only:
            print(f"  note: overwriting profile-only mcpServers: {', '.join(sorted(profile_only))}")

    profile_data["mcpServers"] = source_servers
    profile_claude_json.write_text(json.dumps(profile_data, indent=2) + "\n")

    server_count = len(source_servers) if isinstance(source_servers, dict) else 0
    print(f"  synced mcpServers ({server_count} server{'s' if server_count != 1 else ''})")


def patch_settings_json(
    profile_name: str,
    profile_dir: Path,
    profile_config: dict,
) -> None:
    """Patch per-profile settings (attribution, plansDirectory) into settings.json."""
    patches: dict[str, object] = {}
    if (attribution := profile_config.get("attribution")) is not None:
        patches["attribution"] = attribution
    if (plans_directory := profile_config.get("plansDirectory")) is not None:
        patches["plansDirectory"] = os.path.expanduser(plans_directory)

    settings_path = profile_dir / "settings.json"
    if not settings_path.exists():
        return

    try:
        data = json.loads(settings_path.read_text())
    except (json.JSONDecodeError, OSError):
        return

    if "plansDirectory" not in patches and isinstance(existing := data.get("plansDirectory"), str):
        expanded = os.path.expanduser(existing)
        if expanded != existing:
            patches["plansDirectory"] = expanded

    if not patches:
        return

    changed = [key for key, value in patches.items() if data.get(key) != value]
    if not changed:
        return

    data.update(patches)
    settings_path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    print(f"  patched {', '.join(changed)} in settings.json")


def generate_wrapper_script(
    profile_name: str,
    profile_dir: Path,
    description: str,
    env_vars: dict[str, str],
    add_dirs: list[str],
    model: str | None = None,
    attribution_helper: Path | None = None,
) -> str:
    lines = [
        "#!/usr/bin/env bash",
        MARKER,
        f"# Profile: {profile_name} — {description}",
        "set -euo pipefail",
        "",
        "# Unset inherited CLAUDE_*/ANTHROPIC_* env vars to avoid interference",
        "# when nesting (running from within another Claude Code session).",
        'while IFS= read -r varname; do',
        '  unset "$varname"',
        'done < <(compgen -v | grep -E "^(CLAUDE_|ANTHROPIC_)")',
        "",
        f'export CLAUDE_CONFIG_DIR="{profile_dir}"',
        f'export FP_CC_AUTH_SWITCH_PROFILE="{profile_name}"',
    ]

    for key, value in sorted(env_vars.items()):
        lines.append(f'export {key}="{value}"')

    lines.append("")

    # Subcommands (mcp, auth, etc.) reject --add-dir, --model and other session options with
    # "unknown option", so pass through args directly when a subcommand is detected.
    subcommands = (
        "mcp|auth|doctor|install|setup-token|update|upgrade|agents|auto-mode|plugin|plugins"
        "|attach|logs|respawn|rm|stop|kill|purge|import|gateway|ultrareview"
    )
    lines.extend([
        f'case "${{1:-}}" in',
        f'  {subcommands}) exec claude "$@" ;;',
        'esac',
        '',
    ])

    # When a default model is configured, check if the user already passed --model
    # on the command line — user's --model always takes precedence.
    if model:
        lines.extend([
            f'# Default model (overridden if --model is passed on command line)',
            'user_args=("$@")',
            'has_model=false',
            'for arg in "$@"; do',
            '  case "$arg" in',
            '    --model|--model=*) has_model=true; break ;;',
            '  esac',
            'done',
            f'if [[ "$has_model" == false ]]; then',
            f'  user_args+=(--model "{model}")',
            'fi',
            '',
        ])

    # Attribution from the git config of the launch directory, passed as --settings. Claude Code
    # keeps only the last --settings flag, so a --settings from the user replaces this one entirely;
    # the wrapper then leaves it out. A missing or failing helper only costs the override.
    if attribution_helper is not None:
        lines.extend([
            '# Attribution from [claude-code "attribution"] in git config (skipped when --settings is passed)',
            'settings_args=()',
            'has_settings=false',
            'for arg in "$@"; do',
            '  case "$arg" in',
            '    --settings|--settings=*) has_settings=true; break ;;',
            '  esac',
            'done',
            'if [[ "$has_settings" == false ]]; then',
            f'  attribution_helper="{attribution_helper}"',
            '  if [[ ! -x "$attribution_helper" ]]; then',
            f'    echo "claude-{profile_name}: $attribution_helper is missing, launching without git config attribution" >&2',
            '  elif settings_json=$("$attribution_helper" "$PWD"); then',
            '    if [[ -n "$settings_json" ]]; then',
            '      settings_args=(--settings "$settings_json")',
            '    fi',
            '  else',
            f'    echo "claude-{profile_name}: $attribution_helper failed, launching without git config attribution" >&2',
            '  fi',
            'fi',
            '',
        ])

    cmd_parts = ["exec claude"]
    for d in add_dirs:
        expanded = expand_path(d)
        cmd_parts.append(f'--add-dir "{expanded}"')
    if attribution_helper is not None:
        # bash before 4.4 treats an empty array as unset under set -u, hence the ${x[@]+...} form.
        cmd_parts.append('${settings_args[@]+"${settings_args[@]}"}')
    cmd_parts.append('"${user_args[@]}"' if model else '"$@"')

    lines.append(" \\\n  ".join(cmd_parts))
    return "\n".join(lines) + "\n"


def install_wrapper_script(script_path: Path, content: str) -> None:
    script_path.parent.mkdir(parents=True, exist_ok=True)

    existing = None
    if script_path.exists():
        existing = script_path.read_text()

    if existing == content:
        return

    script_path.write_text(content)
    script_path.chmod(script_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"  installed {script_path}")


def cleanup_stale_scripts(bin_dir: Path, active_script_names: set[str]) -> None:
    if not bin_dir.exists():
        return
    for entry in bin_dir.iterdir():
        if not entry.is_file():
            continue
        if entry.name in active_script_names:
            continue
        try:
            content = entry.read_text()
        except (OSError, UnicodeDecodeError):
            continue
        if MARKER in content:
            entry.unlink()
            print(f"  removed stale script {entry}")


def build_expected_settings(source_path: Path, profile_config: dict) -> str | None:
    """Build what a profile's settings.json should look like after patching.

    Applies config-driven patches (like attribution) to the source content,
    so that divergence detection only flags truly unexpected changes.
    """
    if not source_path.exists():
        return None

    try:
        data = json.loads(source_path.read_text())
    except (json.JSONDecodeError, OSError):
        return None

    if (attribution := profile_config.get("attribution")) is not None:
        data["attribution"] = attribution
    if (plans_directory := profile_config.get("plansDirectory")) is not None:
        data["plansDirectory"] = os.path.expanduser(plans_directory)

    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def collect_diverged_files(
    config: dict,
    profiles_base: Path,
    source_dir: Path,
) -> list[tuple[str, str, str]]:
    """Check all profile copy files for divergence from source.

    Returns list of (profile_name, filename, diff_text) for files where
    the profile copy contains content not present in the source.
    For settings.json, the expected content includes config-driven patches
    (e.g. attribution), so those don't count as divergence.
    """
    diverged = []
    copy_files = resolve_copy_files(source_dir)
    for profile_name, profile_config in config["profiles"].items():
        profile_config = profile_config or {}
        profile_dir = profiles_base / profile_name
        for filename in copy_files:
            src = source_dir / filename
            dst = profile_dir / filename
            if not src.exists() or not dst.exists():
                continue

            if filename == "settings.json":
                expected = build_expected_settings(src, profile_config)
                if expected is None:
                    continue
                src_lines = expected.splitlines(keepends=True)
            else:
                src_lines = src.read_text().splitlines(keepends=True)

            dst_lines = dst.read_text().splitlines(keepends=True)
            diff = list(difflib.unified_diff(
                src_lines, dst_lines,
                fromfile=str(src),
                tofile=str(dst),
            ))
            if not diff:
                continue
            # Check if profile has any additions (content not in source)
            has_additions = any(
                line.startswith('+') and not line.startswith('+++')
                for line in diff
            )
            if has_additions:
                diverged.append((profile_name, filename, ''.join(diff)))
    return diverged


def read_config(config_arg: Path | None) -> tuple[Path, dict]:
    config_path = resolve_config_path(config_arg, DEFAULT_CONFIG_PATH, LEGACY_CONFIG_PATH)
    if not config_path.exists():
        print(f"Error: Config file not found: {config_path}", file=sys.stderr)
        print("Create it from config.example.yaml in the repository:", file=sys.stderr)
        print("  cp config.example.yaml ~/.claude/auth-switch.yaml", file=sys.stderr)
        sys.exit(1)
    return config_path, load_config(config_path)


def install(config_arg: Path | None, sync: bool, force: bool) -> None:
    config_path, config = read_config(config_arg)
    source_dir = expand_path(config.get("source_dir", str(DEFAULT_SOURCE_DIR)))
    bin_dir = expand_path(config.get("bin_dir", str(DEFAULT_BIN_DIR)))
    profiles_base = expand_path(config.get("profiles_dir", str(DEFAULT_PROFILES_DIR)))

    secrets_path = secrets_path_for(config_path)
    secrets: dict[str, dict[str, str]] = {}
    if secrets_path.exists():
        check_secrets_git_safety(secrets_path)
        secrets = load_secrets(secrets_path, config)

    if not source_dir.exists():
        print(f"Error: Source directory not found: {source_dir}", file=sys.stderr)
        sys.exit(1)

    # When --sync is used without --force, check for diverged files first
    if sync and not force:
        diverged = collect_diverged_files(config, profiles_base, source_dir)
        if diverged:
            print("\nDiverged profile files detected:\n")
            for profile_name, filename, diff_text in diverged:
                print(f"  Profile '{profile_name}' — {filename}:")
                for line in diff_text.splitlines():
                    print(f"    {line}")
                print()
            print("The profile file(s) above contain changes not present in the source.")
            print("You probably want to merge these changes back to the source file first.")
            print("\nTo overwrite anyway, use: claude-code-auth-switch install --sync --force")
            sys.exit(0)

    source_claude_json_path = Path.home() / ".claude.json"
    attribution_helper = resolve_command(ATTRIBUTION_HELPER_NAME)
    active_script_names: set[str] = set()

    for profile_name, profile_config in config["profiles"].items():
        profile_config = profile_config or {}
        description = profile_config.get("description", "")
        env_vars = profile_config.get("env", {}) or {}
        add_dirs = profile_config.get("add_dirs", []) or []
        model = profile_config.get("model") or None
        pinned_models = profile_config.get("pinned_models", {}) or {}

        env_vars = merge_secret_env(profile_name, env_vars, secrets.get(profile_name, {}))

        # Pin alias→version via ANTHROPIC_DEFAULT_<CLASS>_MODEL vars, merged so an explicit
        # env: entry for the same var wins over the pinned_models-derived value.
        pinned_env = pinned_models_to_env(profile_name, pinned_models)
        env_vars = {**pinned_env, **env_vars}

        profile_dir = profiles_base / profile_name
        script_name = f"claude-{profile_name}"
        script_path = bin_dir / script_name
        active_script_names.add(script_name)

        print(f"\nProfile: {profile_name}")

        # Setup profile directory with copies and symlinks
        setup_profile_dir(profile_name, profile_dir, source_dir, sync)

        # Patch attribution settings into profile's settings.json
        patch_settings_json(profile_name, profile_dir, profile_config)

        # Sync mcpServers from global ~/.claude.json
        sync_mcp_servers(profile_name, profile_dir, source_claude_json_path)

        # Generate and install wrapper script
        content = generate_wrapper_script(
            profile_name, profile_dir, description, env_vars, add_dirs, model, attribution_helper,
        )
        install_wrapper_script(script_path, content)

    # Clean up stale wrapper scripts
    print("\nCleanup:")
    cleanup_stale_scripts(bin_dir, active_script_names)

    print("\nDone.")
